export type TranslationKey = keyof typeof en;
export type Translations = typeof en;

const translations: Record<Locale, Translations> = { en, hy, ru };

export function t(locale: Locale, key: TranslationKey, vars?: Record<string, string>): string {
  let str = translations[locale]?.[key] ?? translations.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(`{${k}}`, v);
    }
  }
  return str;
}

export function getLocale(nativeLanguage?: string | null): Locale {
  if (nativeLanguage === "hy") return "hy";
  if (nativeLanguage === "ru") return "ru";
  return "en";
}
